#!/usr/bin/env python3
"""Turn docs/site/seo/meta.json (the SEO handoff, [uz, ru, en]) into content/site/seo.ts.

The app's tuples are [en, uz, ru], and the product name is never typed: "DocMaster"
becomes {brand}, which t-style substitution fills from runtimeConfig.public.productName.
Run again whenever meta.json changes: python3 scripts/site/seo-meta.py
"""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[2]
meta = json.loads((root / 'docs/site/seo/meta.json').read_text(encoding='utf-8'))
FIELDS = ('title', 'description', 'ogTitle')


def tuple_of(values):
    uz, ru, en = (value.replace('DocMaster', '{brand}') for value in values)
    return '[' + ', '.join(json.dumps(text, ensure_ascii=False) for text in (en, uz, ru)) + ']'


lines = [
    '// Generated by scripts/site/seo-meta.py from docs/site/seo/meta.json. Do not edit by hand.',
    '// Each text is [en, uz, ru]; {brand} is the product name.',
    'export type SeoText = readonly [string, string, string]',
    'export type PageSeo = { title: SeoText; description: SeoText; ogTitle?: SeoText; noindex?: boolean }',
    'export const pageSeo: Record<string, PageSeo> = {',
]
for page, entry in meta.items():
    parts = [f'{field}: {tuple_of(entry[field])}' for field in FIELDS if field in entry]
    if entry.get('noindex'):
        parts.append('noindex: true')
    lines.append(f'  {json.dumps(page)}: {{ ' + ', '.join(parts) + ' },')
lines.append('}')
(root / 'content/site/seo.ts').write_text('\n'.join(lines) + '\n', encoding='utf-8')
print(f'{len(meta)} pages written')
